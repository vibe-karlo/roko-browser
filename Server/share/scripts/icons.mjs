// Copies the app's Phosphor topic icons (MIT) into src/icons.js, so a shared
// page draws its sections with the same icons as the app.
//
//     node scripts/icons.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const assets = new URL("../../../Browser/Resources/Assets.xcassets/phosphor/", import.meta.url).pathname;
const icons = {};
for (const folder of readdirSync(assets).filter((name) => name.startsWith("topic-")).sort()) {
  const name = folder.replace(/^topic-/, "").replace(/\.imageset$/, "");
  const svg = readFileSync(join(assets, folder, `topic-${name}.svg`), "utf8");
  // Just the drawing: the page sets the size and colour.
  icons[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*fill="[^"]*"/g, "");
}

const body = Object.entries(icons).map(([name, paths]) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`).join("\n");
writeFileSync(new URL("../src/icons.js", import.meta.url),
  `// Generated by scripts/icons.mjs from the app's Phosphor icons (MIT). Don't edit.\nexport const TOPIC_ICONS = {\n${body}\n};\n`);
console.log(`${Object.keys(icons).length} icons`);
